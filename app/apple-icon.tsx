export default function AppleIcon() {
  const s = size.width;
  const rows = J_MAP.length;
  const cols = J_MAP[0].length;
  const cell = s / cols;

  const cells: React.ReactElement[] = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (J_MAP[r][c] !== "1") continue;
      cells.push(
        <div
          key={`${r}-${c}`}
          style={{
            position: "absolute",
            left: c * cell,
            top: r * cell,
            width: cell + 0.4,
            height: cell + 0.4,
            backgroundColor: "#000000",
          }}
        />,
      );
    }
  }

  return new ImageResponse(
    (
      <div
        style={{
          width: "100%",
          height: "100%",
          backgroundColor: "#ffffff",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
        }}
      >
        <div
          style={{
            width: s,
            height: s,
            borderRadius: "50%",
            backgroundColor: "#ffffff",
            position: "relative",
            display: "flex",
            overflow: "hidden",
          }}
        >
          {cells}
        </div>
      </div>
    ),
    { ...size },
  );
}
